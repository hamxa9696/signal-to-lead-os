// Planning weeks run Monday–Sunday in Japan time.

/** Today's date in Asia/Tokyo as YYYY-MM-DD. */
export function tokyoToday(now = new Date()): string {
  return new Intl.DateTimeFormat("en-CA", { timeZone: "Asia/Tokyo" }).format(now);
}

/** Monday (YYYY-MM-DD) of the Tokyo week containing `now`. */
export function weekOf(now = new Date()): string {
  const d = new Date(`${tokyoToday(now)}T00:00:00Z`);
  const dow = (d.getUTCDay() + 6) % 7; // Mon=0 … Sun=6
  d.setUTCDate(d.getUTCDate() - dow);
  return d.toISOString().slice(0, 10);
}

export function addDays(isoDate: string, days: number): string {
  const d = new Date(`${isoDate}T00:00:00Z`);
  d.setUTCDate(d.getUTCDate() + days);
  return d.toISOString().slice(0, 10);
}
